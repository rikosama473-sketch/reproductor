import assert from "node:assert/strict";
import { MAX_PLAYLIST_NAME_LENGTH, normalizePlaylistName, renamePlaylist, movePlaylistTrack, removePlaylistTrack } from "../src/playlist-editing.js";
const source = { id: "list-1", name: "Mi lista", trackIds: ["a", "b", "c"], createdAt: 100, updatedAt: 200, customMetadata: "preserved" };
assert.equal(MAX_PLAYLIST_NAME_LENGTH, 80);
assert.equal(normalizePlaylistName("  Mi   lista " + String.fromCharCode(9) + " favorita  "), "Mi lista favorita");
assert.equal(normalizePlaylistName("Café"), "Café");
assert.throws(() => normalizePlaylistName("  "), /nombre/i);
assert.throws(() => normalizePlaylistName(null), /nombre/i);
assert.throws(() => normalizePlaylistName("x".repeat(81)), /80 caracteres/i);
assert.equal(normalizePlaylistName("x".repeat(80)).length, 80);
const renamed = renamePlaylist(source, "  Música   para escribir  ", 300);
assert.deepEqual(renamed, { ...source, name: "Música para escribir", updatedAt: 300 });
assert.equal(source.name, "Mi lista", "Rename must not mutate the original");
assert.throws(() => renamePlaylist(source, " "), /nombre/i);
assert.throws(() => renamePlaylist(source, "x".repeat(81)), /80 caracteres/i);
assert.throws(() => renamePlaylist(null, "Nueva"), /lista/i);
assert.deepEqual(movePlaylistTrack(source, "b", -1, 301).trackIds, ["b", "a", "c"]);
assert.deepEqual(movePlaylistTrack(source, "b", 1, 302).trackIds, ["a", "c", "b"]);
assert.equal(movePlaylistTrack(source, "a", -1, 303), null);
assert.equal(movePlaylistTrack(source, "c", 1, 303), null);
assert.equal(movePlaylistTrack(source, "missing", 1, 303), null);
assert.throws(() => movePlaylistTrack(source, "a", 0, 303), /dirección/i);
assert.deepEqual(source.trackIds, ["a", "b", "c"], "Move must not mutate order");
const removed = removePlaylistTrack(source, "b", 304);
assert.deepEqual(removed.trackIds, ["a", "c"]);
assert.equal(removed.updatedAt, 304);
assert.equal(removed.customMetadata, "preserved");
assert.deepEqual(source.trackIds, ["a", "b", "c"], "Removal must not mutate source");
assert.equal(removePlaylistTrack(source, "missing", 305), null);
assert.throws(() => removePlaylistTrack({ ...source, trackIds: null }, "a"), /lista/i);
assert.throws(() => renamePlaylist(source, "válida", -1), /fecha/i);
console.log("Playlist editing checks passed: normalized names, immutable updates, movement boundaries and removal.");
